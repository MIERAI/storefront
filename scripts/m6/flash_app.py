#!/usr/bin/env python3
"""The flash-sale capacity test as an app.yaml for slo-platform's capacity runner (scripts/capacity.py, run from
winpc by ~/workspace/gitops/bin/loadtest.sh). Only what capacity.py reads: name / environments (its namespace is
<name>-<env>, so v2-lab = name v2, env lab), the SLOs a step is judged on, and `capacity:`.

  flash_app.py [--namespace v2-lab] [--order-port 8080] [--pg-cluster postgres] [--rabbitmq rabbitmq] \
               [--out out/flash-sale.app.yaml]

The load: PlaceOrder of 1 unit of one of three hot SKUs (M6-FLASH-1..3, stock topped up by seed.js), open loop.
A step holds when all three hold over the step:
  placement-availability  PlaceOrder without a server error          99.5%   (the synchronous path: order's own DB)
  placement-latency       PlaceOrder within 0.5s                     99%
  saga-keeps-up           orders final within 10s (OrderSaga)         99%    (the asynchronous path: the hot stock rows
                                                                              in inventory, payment, the relays)
The last one is what makes this a flash-sale test rather than a PlaceOrder test: placing an order only writes order's
database (design §6.3); the contention is in inventory's conditional UPDATE on three rows. 10s (a bucket edge of
factory_sm_completion_seconds) is "keeps up": a normal order completes in about a second, so a backlog that grows
crosses it within one step, long before the 60s journey SLO. "10.0", not "10": Prometheus 3 stores integer bucket edges
as le="10.0", and capacity.py matches the threshold literally. Reported workloads: order first (per pod), then
inventory, payment, notification, Postgres and RabbitMQ (their CPU tells which ran out).
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLACE = "/order.order.v1.OrderService/PlaceOrder"


def render(ns, order_port, pg, rabbit):
    if "-" not in ns:
        raise SystemExit(f"namespace {ns}: capacity.py needs <name>-<env>")
    name, env = ns.rsplit("-", 1)
    body = lambda sku: json.dumps({"customer_id": "7{rand}{rand}",
                                   "items": [{"line_no": 1, "sku": sku, "qty": 1, "price": "9.99"}]}, separators=(",", ":"))
    return {
        "name": name,
        "environments": [{"name": env}],
        "slos": [
            {"name": "placement-availability", "objective": 99.5,
             "availability": {"metric": "rpc_requests_total", "matchers": f'procedure="{PLACE}"',
                              "errors": 'code=~"internal|unavailable|unknown|deadline_exceeded|data_loss|resource_exhausted"'}},
            {"name": "placement-latency", "objective": 99,
             "latency": {"metric": "rpc_request_duration_seconds", "matchers": f'procedure="{PLACE}"', "threshold": "0.5"}},
            {"name": "saga-keeps-up", "objective": 99,
             "latency": {"metric": "factory_sm_completion_seconds", "matchers": 'machine="OrderSaga"', "threshold": "10.0"}},
        ],
        "capacity": {
            "slos": ["placement-availability", "placement-latency", "saga-keeps-up"],
            "workloads": ["order", "inventory", "payment", "notification"] + [w for w in (pg, rabbit) if w],
            "requests": [{"weight": 1, "method": "POST", "service": "order", "port": order_port, "path": PLACE,
                          "body": body(f"M6-FLASH-{i}")} for i in (1, 2, 3)],
            "ramp": {"start": 10, "factor": 2, "max": 1600, "step": "90s", "warmup": "30s", "refine": 3, "confirm": 1, "headroom": 0.7},
        },
    }


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--namespace", default=os.environ.get("M6_NAMESPACE", "v2-lab"))
    p.add_argument("--order-port", type=int, default=8080)
    p.add_argument("--pg-cluster", default="postgres")
    p.add_argument("--rabbitmq", default="rabbitmq")
    p.add_argument("--out", default=os.path.join(HERE, "out", "flash-sale.app.yaml"))
    a = p.parse_args()
    doc = render(a.namespace, a.order_port, a.pg_cluster, a.rabbitmq)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("# generated by scripts/m6/flash_app.py (storefront) for slo-platform capacity.py: do not edit, re-run it\n")
        json.dump(doc, f, indent=2)   # JSON is YAML
        f.write("\n")
    print(f"→ {a.out}  (namespace {a.namespace}: name {doc['name']}, env {doc['environments'][0]['name']})")


if __name__ == "__main__":
    main()
