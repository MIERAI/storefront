var page = template.Must(template.New("").Parse(`<!doctype html><meta charset="utf-8"><title>storefront</title>
<h1>storefront</h1><p>today: free shipping over ¥3000</p><p>web {{.Web}} · {{.Source}} {{or .Version "unreachable"}}</p>
<ul>{{range .Products}}<li>{{.Name}} — ¥{{.Price}}</li>{{end}}</ul>`))

// shelf: what the page shows. Products nil = the products could not be had (a degraded page).
type shelf struct {
	Source, Version string // "api" / "catalog" and its version ("" = unknown)
	Products        []item
}

type item struct{ Name, Price string } // price as text: v1 has yen as integers, the catalog decimals as text

// browse gets the products for one page request (r's trace continues in the call).
type browse func(ctx context.Context) shelf

// fromAPI: v1, GET API_URL/products → {"version": "…", "products": [{"name": "…", "price": 1200}]}.
func fromAPI(apiURL string, client *http.Client) browse {
	return func(ctx context.Context) shelf {
		var p struct {
			Version  string `json:"version"`
			Products []struct {
				Name  string `json:"name"`
				Price int    `json:"price"`
			} `json:"products"`
		}
		s := shelf{Source: "api"}
		req, err := http.NewRequestWithContext(ctx, "GET", apiURL+"/products", nil)
		var resp *http.Response
		if err == nil {
			resp, err = client.Do(req)
		}
		if err != nil {
			return s
		}
		defer resp.Body.Close()
		if resp.StatusCode != http.StatusOK || json.NewDecoder(resp.Body).Decode(&p) != nil || p.Products == nil {
			return s
		}
		s.Version, s.Products = p.Version, []item{}
		for _, x := range p.Products {
			s.Products = append(s.Products, item{x.Name, fmt.Sprint(x.Price)})
		}
		return s
	}
}

// fromCatalog: v2 step S1, the catalog's ListProducts (Connect, JSON) per category, every page of it.
func fromCatalog(catalogURL string, categories []string, client *http.Client) browse {
	v := &catalogVersion{url: catalogURL, client: client}
	return func(ctx context.Context) shelf {
		s := shelf{Source: "catalog", Version: v.get(ctx)}
		var all []item
		for _, c := range categories {
			items, err := listProducts(ctx, client, catalogURL, c)
			if err != nil {
				slog.Warn("catalog ListProducts", "category", c, "err", err)
				return s
			}
			all = append(all, items...)
		}
		s.Products = append([]item{}, all...)
		return s
	}
}

const listProductsPath = "/catalog.catalog.v1.CatalogService/ListProducts"

func listProducts(ctx context.Context, client *http.Client, base, category string) ([]item, error) {
	var items []item
	token := ""
	for range 10 { // ≤ 1000 products per category: plenty for this shop, and a bound on a looping token
		body, _ := json.Marshal(map[string]any{"category": category, "pageSize": 100, "pageToken": token})
		req, err := http.NewRequestWithContext(ctx, "POST", base+listProductsPath, bytes.NewReader(body))
		if err != nil {
			return nil, err
		}
		req.Header.Set("Content-Type", "application/json")
		resp, err := client.Do(req)
		if err != nil {
			return nil, err
		}
		var out struct {
			Products []struct {
				Name  string `json:"name"`
				Price string `json:"price"`
			} `json:"products"`
			NextPageToken string `json:"nextPageToken"`
		}
		err = json.NewDecoder(resp.Body).Decode(&out)
		resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			return nil, fmt.Errorf("%s: %d", listProductsPath, resp.StatusCode)
		}
		if err != nil {
			return nil, err
		}
		for _, p := range out.Products {
			items = append(items, item{p.Name, p.Price})
		}
		if token = out.NextPageToken; token == "" {
			return items, nil
		}
	}
	return items, nil
}

// catalogVersion: the catalog's X-App-Version from its /healthz, asked at most every 30s ("" while unknown).
type catalogVersion struct {
	url    string
	client *http.Client
	mu     sync.Mutex
	value  string
	at     time.Time
}

func (v *catalogVersion) get(ctx context.Context) string {
	v.mu.Lock()
	defer v.mu.Unlock()
	if time.Since(v.at) < 30*time.Second {
		return v.value
	}
	v.at = time.Now()
	req, err := http.NewRequestWithContext(ctx, "GET", v.url+"/healthz", nil)
	if err != nil {
		return v.value
	}
	if resp, err := v.client.Do(req); err == nil {
		resp.Body.Close()
		if h := resp.Header.Get("X-App-Version"); resp.StatusCode == http.StatusOK && h != "" {
			v.value = h
		}
	}
	return v.value
}

// createOrder stores an order (orders.Create; nil: no database configured).
type createOrder func(ctx context.Context, amount int) (int64, error)

func newMux(version string, products browse, create createOrder, m *obs.Metrics) *http.ServeMux {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("X-App-Version", version)
		w.Write([]byte("ok"))
	})
	mux.HandleFunc("GET /{$}", func(w http.ResponseWriter, r *http.Request) {
		s := products(r.Context())
		if s.Products == nil {
			obs.Degraded(w)
		}
		page.Execute(w, map[string]any{"Web": version, "Source": s.Source, "Version": s.Version, "Products": s.Products})
	})
	mux.HandleFunc("POST /orders", func(w http.ResponseWriter, r *http.Request) {
		var o struct {
			Amount int `json:"amount"`
		}
		if json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<10)).Decode(&o) != nil || o.Amount <= 0 || o.Amount > 1_000_000 {
			http.Error(w, `{"error":"amount: a positive number of yen"}`, http.StatusBadRequest)
			return
		}
		if create == nil {
			http.Error(w, `{"error":"orders are not available"}`, http.StatusServiceUnavailable)
			return
		}
		ctx, cancel := context.WithTimeout(r.Context(), 2*time.Second)
		defer cancel()
		id, err := create(ctx, o.Amount)
		if err != nil {
			slog.Error("create order", "err", err)
			http.Error(w, `{"error":"the order could not be stored, try again"}`, http.StatusServiceUnavailable)
			return
		}
		m.Inc("orders_created_total")
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusCreated)
		json.NewEncoder(w).Encode(map[string]int64{"id": id})
	})
	return mux
}

// watch runs orders.Check every interval and exports what it sees.
func watch(ctx context.Context, db *pgxpool.Pool, m *obs.Metrics, interval, deadline time.Duration) {
	for {
		c, cancel := context.WithTimeout(ctx, interval)
		s, err := orders.Check(c, db, deadline)
		cancel()
		if err != nil {
			slog.Warn("check orders", "err", err)
			m.Unset("orders_pending")
			m.Unset("orders_oldest_pending_age_seconds")
			m.Unset("orders_processed_through_timestamp_seconds")
		} else {
			m.Set("orders_processed_through_timestamp_seconds", float64(s.Through.UnixMilli())/1000)
			m.Set("orders_pending", float64(s.Pending))
			m.Set("orders_oldest_pending_age_seconds", s.OldestAge.Seconds())
		}
		m.Add("orders_overdue_total", uint64(s.Overdue))
		select {
		case <-ctx.Done():
			return
		case <-time.After(interval):
		}
	}
}

func envOr(env, def string) string {
	if v := os.Getenv(env); v != "" {
		return v
	}
	return def
}

func duration(env string, def time.Duration) time.Duration {
	if d, err := time.ParseDuration(os.Getenv(env)); err == nil {
		return d
	}
	return def
}

func main() {
	version, apiURL := os.Getenv("APP_VERSION"), os.Getenv("API_URL")
	obs.Tracing(context.Background(), "web", version) // no graceful stop here: the last batch (≤5s of spans) is lost on SIGTERM
	m := obs.New()
	m.Add("orders_created_total", 0)
	m.Add("orders_overdue_total", 0)
	m.Serve(":9090")
	products := fromAPI(apiURL, m.Client("api", &http.Client{Timeout: 2 * time.Second}))
	catalogURL := os.Getenv("CATALOG_URL")
	if catalogURL != "" {
		categories := strings.Split(envOr("CATALOG_CATEGORIES", "coffee,goods"), ",")
		products = fromCatalog(catalogURL, categories, m.Client("catalog", &http.Client{Timeout: 2 * time.Second}))
	}
	var create createOrder
	if url := os.Getenv("DATABASE_URL"); url != "" {
		db, err := orders.Open(context.Background(), url) // connects lazily: the page is served without a database
		if err != nil {
			slog.Error("DATABASE_URL", "err", err)
			os.Exit(1)
		}
		create = func(ctx context.Context, amount int) (int64, error) { return orders.Create(ctx, db, amount) }
		go func() {
			for err := orders.Migrate(context.Background(), db); err != nil; err = orders.Migrate(context.Background(), db) {
				slog.Warn("migrate (retrying)", "err", err)
				time.Sleep(5 * time.Second)
			}
			watch(context.Background(), db, m, duration("CHECK_INTERVAL", 10*time.Second), duration("ORDER_DEADLINE", 5*time.Minute))
		}()
	}
	srv := &http.Server{Addr: ":8080", Handler: m.Instrument(newMux(version, products, create, m)), ReadHeaderTimeout: 5 * time.Second}
	slog.Info("web listening", "version", version, "api", apiURL, "catalog", catalogURL)
	if err := srv.ListenAndServe(); err != nil {
		slog.Error("serve", "err", err)
		os.Exit(1)
	}
}
