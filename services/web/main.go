// web: the storefront's page (a service of this monorepo, released and promoted on its own). It renders the
// products of the catalog service (CATALOG_URL; storefront v2 step S1) — or, where CATALOG_URL is not set, of the v1
// api service (API_URL) — and shows both versions: which web and which catalog / api an environment runs.
//
//	GET /        → HTML page; without the products it is still served (200) but counted degraded: a bad event for
//	               the availability SLO (obs.Degraded)
//	POST /orders → {"amount": 1200} → 201 {"id": n}: a pending order in Postgres (DATABASE_URL), processed later
//	               by the worker; 400 for a bad amount, 503 when the order cannot be stored
//	GET /healthz → ok (header X-App-Version)
//	:9090 /metrics (internal/obs); calls to the api / catalog are counted as upstream "api" / "catalog"
//	traces (internal/obs Tracing, OTEL_* environment): server spans, the call to the api / catalog, the order INSERT
//
// The catalog (services/catalog, generated by api-factory) is asked with the Connect protocol (JSON over HTTP, no
// generated client needed here): ListProducts once per category of CATALOG_CATEGORIES (default "coffee,goods"; the
// API lists one category). Any failed call = no products = a degraded page. The catalog's version comes from its
// /healthz (X-App-Version), asked at most every 30s.
//
// web also watches the order pipeline from the outside (internal/orders Check, every CHECK_INTERVAL): a gauge
// exported by the worker would vanish with the last worker, exactly when it matters.
//
//	orders_created_total                     orders accepted
//	orders_processed_through_timestamp_seconds   every order created before it is processed (the oldest
//	                                         unprocessed order's creation time, or now): freshness SLI = time() - it.
//	                                         Absent while the database cannot be asked (unknown is not fresh)
//	orders_pending, orders_oldest_pending_age_seconds   backlog (dashboards)
//	orders_overdue_total                     orders not processed ORDER_DEADLINE after creation (completeness SLI:
//	                                         bad events among orders_created_total), each counted once
package main

