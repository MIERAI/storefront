-- storefront v2 · inventory (库存). This service's own database.
CREATE TABLE IF NOT EXISTS stock (
    sku         TEXT        NOT NULL PRIMARY KEY CHECK (sku ~ '^[A-Z0-9-]{3,32}$'),
    available   INTEGER     NOT NULL CHECK (available >= 0),   -- never negative: no overselling
    reserved    INTEGER     NOT NULL DEFAULT 0 CHECK (reserved >= 0),
    version     INTEGER     NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A reservation of an order (the saga's step 1); committed or released later (R3–R5 write it).
CREATE TABLE IF NOT EXISTS reservations (
    order_id    BIGINT      NOT NULL,
    sku         TEXT        NOT NULL,
    qty         INTEGER     NOT NULL CHECK (qty > 0),
    status      INTEGER     NOT NULL DEFAULT 1 CHECK (status IN (1, 2, 3)),   -- 1 held, 2 committed, 3 released
    expires_at  TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '24 hours'),   -- a safety net only (R5 drives the saga)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (order_id, sku)
);
CREATE INDEX IF NOT EXISTS reservations_expiry_idx ON reservations (expires_at) WHERE status = 1;

-- An audit row per stock adjustment (W4 AdjustStock: written in the same transaction as the change of stock.available).
CREATE TABLE IF NOT EXISTS stock_adjustments (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         TEXT        NOT NULL REFERENCES stock (sku),
    delta       INTEGER     NOT NULL,                                       -- + received, - removed; 0 = a stocktake without a difference
    reason      INTEGER     NOT NULL CHECK (reason IN (1, 2, 3)),           -- 1 received, 2 stocktake, 3 damaged
    adjusted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_adjustments_sku_idx ON stock_adjustments (sku, adjusted_at);
